export function lookupPrice(description: string): number {
  if (PRICE_LOOKUP[description] !== undefined) return PRICE_LOOKUP[description];
  const descLower = description.toLowerCase().replace(/×/g, "x");
  for (const [key, price] of Object.entries(PRICE_LOOKUP)) {
    const keyLower = key.toLowerCase().replace(/×/g, "x");
    if (descLower.includes(keyLower) || keyLower.includes(descLower)) {
      return price;
    }
  }
  return 0;
}

export interface QuoteLineItem {
  id: string;
  category: string;
  description: string;
  requestedQty: number;
  quotedQty: number;
  unit: string;
  unitPrice: number;
  total: number;
  inStock: boolean;
  notes?: string;
  catalogPrice?: number;
  catalogName?: string;
}

export interface SubmittedQuote {
  rfqId: string;
  lumberyardName: string;
  items: QuoteLineItem[];
  subtotal: number;
  deliveryFee: number;
  total: number;
  validUntil: string;
  paymentTerms: string;
  notes?: string;
  submittedAt: string;
}

/** Compute a quote from an RFQ's items using the shared price table. */
export function computeQuoteFromRFQ(
  rfq: { id: string; items: { category: string; description: string; quantity: number; unit: string }[] },
  lumberyardName = "Austin Timber Supply",
  deliveryFee = 150
): SubmittedQuote {
  const items: QuoteLineItem[] = rfq.items.map((item, idx) => {
    const unitPrice = lookupPrice(item.description);
    return {
      id: `item-${idx}`,
      category: item.category,
      description: item.description,
      requestedQty: item.quantity,
      quotedQty: item.quantity,
      unit: item.unit,
      unitPrice,
      total: unitPrice * item.quantity,
      inStock: true,
    };
  });

  const subtotal = items.reduce((s, i) => s + i.total, 0);
  const total = subtotal + deliveryFee;

  // Valid until ~14 days from now
  const validUntilDate = new Date();
  validUntilDate.setDate(validUntilDate.getDate() + 14);

  return {
    rfqId: rfq.id,
    lumberyardName,
    items,
    subtotal,
    deliveryFee,
    total,
    validUntil: validUntilDate.toISOString().split("T")[0],
    paymentTerms: "Net 30",
    submittedAt: new Date().toISOString(),
  };
}
